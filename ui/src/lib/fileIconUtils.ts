const DEFAULT_FILE_META: FileIconMeta = {
  extension: "",
  language: "File",
  iconId: "file",
  symbolId: "icon-file",
  iconPath: "",
  color: "#94A3B8",
  textColorClass: "text-[#57606a] dark:text-[#a0a0a0]",
  badgeBgClass: "bg-slate-500/10 text-slate-600 dark:text-slate-400 border-slate-500/20",
}

/**
 * Highly efficient O(1) file icon & style lookup by filename with VS Code Dark Modern & Light Modern color schemes.
 */
export function getFileIconMeta(filename: string): FileIconMeta {
  if (!filename) return DEFAULT_FILE_META

  const lowerName = filename.toLowerCase()

  // 1. Check exact filename matches (e.g. dockerfile, .gitignore, go.mod)
  if (EXACT_FILENAME_MAP[lowerName]) {
    return EXACT_FILENAME_MAP[lowerName]
  }

  // 2. Check compound extensions (.d.ts, .test.tsx, .config.js)
  const parts = lowerName.split(".")
  if (parts.length > 2) {
    const compoundExt = parts.slice(-2).join(".")
    if (EXTENSION_MAP[compoundExt]) {
      return EXTENSION_MAP[compoundExt]
    }
  }

  // 3. Check single extension
  const ext = parts.pop() || ""
  if (EXTENSION_MAP[ext]) {
    return EXTENSION_MAP[ext]
  }

  return DEFAULT_FILE_META
}
